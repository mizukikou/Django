# ==============================================================================
# 🎯 ITS 資訊科技專家認證：多變數線性回歸（Multiple Linear Regression）專案
# ==============================================================================
# 本腳本完整實作了機器學習標準流程：資料預處理 -> 特徵工程 -> 模型訓練 -> 評估 -> 預測新案例
# 執行前請確保已於虛擬環境中安裝：pip install pandas scikit-learn matplotlib numpy

import pandas as pd              # 數據分析核心套件，用於建立與操作 DataFrame 欄位表格
import matplotlib.pyplot as plt  # 2D 繪圖函式庫，用於將實際值與預測值的落點可視化
import numpy as np               # 科學計算套件，提供高效率的多維陣列操作與數學開根號計算
import pickle                    # 物件序列化套件，能將訓練好的模型直接打包封存為二進位檔案

# 從 Scikit-Learn 機器學習庫中引入核心模組：
from sklearn.model_selection import train_test_split  # 用於將完整數據隨機切分為「訓練集」與「測試集」
from sklearn.linear_model import PoissonRegressor     # 使用 log link 的回歸模型，預測值維持為正數
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import mean_absolute_error       # 評估指標：平均絕對誤差（MAE）
from sklearn.metrics import mean_squared_error        # 評估指標：均方誤差（MSE），後續開根號變 RMSE
from sklearn.metrics import r2_score                  # 評估指標：決定係數（R² Score），代表模型解釋力

# 🛠️ 【優化機制】解決 Matplotlib 繪圖時的繁體中文亂碼與符號顯示問題
plt.rcParams["font.sans-serif"] = ["Microsoft JhengHei"] # 強制設定渲染字體為「微軟正黑體」，防止中文變方塊
plt.rcParams["axes.unicode_minus"] = False               # 修正座標軸中「負號 (-)」無法正常顯示的 Bug

# ==============================================================================
# 📈 步驟 1：讀取原始數據（Data Ingestion）
# ==============================================================================
# 使用相對路徑讀取與本腳本放在同一目錄下的房價 CSV 原始資料檔
df = pd.read_csv("./LinearRegressionData.csv", encoding="utf-8")

print("=== [1/11] 原始資料集基本資訊 ===")
print(df.info()) # 印出資料表的維度、欄位型態、非空值（Non-Null）個數與記憶體用量

# ==============================================================================
# 🔀 步驟 2：特徵工程 - 類別變數轉型（One-Hot Encoding）
# ==============================================================================
# 由於線性回歸模型只能接收數字，必須將文字型態的「行政區」欄位轉換為 0 與 1 的二進位虛擬變數（Dummy Variables）。
# drop_first=True：極度重要！它會自動刪除第一個行政區欄位，用來避免統計學上的「多重共線性陷阱（Dummy Variable Trap）」。
# 自動刪除的那第一個行政區，會直接變成「基準點（Baseline）
# 用的模型對「特徵欄位之間的相關性」非常敏感時，就必須開啟 drop_first=True。例如：線性回歸、邏輯回歸。
df = pd.get_dummies(df, columns=["行政區"], drop_first=True)

# 將轉換完畢的乾淨資料輸出備份（使用 utf-8-sig 編碼，確保用 Excel 直接雙擊開啟時中文絕不亂碼）
df.to_csv("./LinearRegressionData_processed.csv", index=False, encoding="utf-8-sig") 

# ==============================================================================
# ✂️ 步驟 3：拆分特徵（X）與目標變數（y）
# ==============================================================================
X = df.drop(["房價萬元", "編號"], axis=1) # X 代表「特徵矩陣」：必須剔除預測目標「房價萬元」與無意義的「編號」欄位
y = df["房價萬元"]                      # y 代表「標籤（Label）」：即我們要預測的實際目標房價

# ==============================================================================
# 🔀 步驟 4：切分訓練集（Train）與測試集（Test）
# ==============================================================================
# test_size=0.2：抽取 20% 的資料作為「測試集」來檢驗模型，剩下的 80% 作為「訓練集」供模型學習
# random_state=100：固定的隨機種子，確保每次執行此程式碼時，切分到的訓練與測試資料完全一致，方便後續對比成果
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.2, random_state=100)

# 將切分後的訓練集資料儲存匯出，保留實驗軌跡
X_train.to_csv("./LinearRegressionData_train_x.csv", index=False, encoding="utf-8-sig") 
y_train.to_csv("./LinearRegressionData_train_y.csv", index=False, encoding="utf-8-sig") 

# ==============================================================================
# 🤖 步驟 5：建立模型與引導機器學習（Model Training）
# ==============================================================================
model = Pipeline([
    ("scaler", StandardScaler()),
    ("regressor", PoissonRegressor(alpha=0.01, max_iter=2000))
])
model.fit(X_train, y_train)    # 呼叫 fit 指令：讓演算法透過最小平方法（OLS）去找出最完美的權重係數與截距

# 【模型持久化】將訓練好的精準模型打包序列化，儲存為二進位檔案，未來可直接載入，不需重新訓練
with open("./LinearRegressionModel.pkl", "wb") as f:
    pickle.dump(model, f) 

# ==============================================================================
# 🔮 步驟 6：載入已儲存的模型並對「測試集」進行預測
# ==============================================================================
with open("./LinearRegressionModel.pkl", "rb") as f:
    model = pickle.load(f)     # 模擬從硬碟讀取模型檔案

y_pred = np.maximum(model.predict(X_test), 0.0) # 房價不可為負，將線性回歸外插的負值限制為 0

# 建立實際房價與預測房價的對照表，方便肉眼直觀對比模型精準度
result = pd.DataFrame({
    "實際房價": y_test.values,
    "預測房價": y_pred
})
print("\n=== [6/11] 測試集前 10 筆預測結果對照 ===")
print(result.head(10))

# ==============================================================================
# 🎯 步驟 7：三大統計指標評估模型效能（Model Evaluation）
# ==============================================================================
print("\n=== [7/11] 機器學習模型評估指標 ===")

# 1. MAE (平均絕對誤差)：計算預測值與實際值差距的絕對值平均。
# 數值代表的含意：平均而言，模型預測出來的房價與真實房價落差了多少萬元。
mae = mean_absolute_error(y_test, y_pred)
print(f"MAE  (平均絕對誤差) = {mae:.2f} 萬元")

# 2. RMSE (均方根誤差)：將誤差平方後取平均、再開根號。
# 數值代表的含意：它對極端的大 Bug（預測大翻車）非常敏感，RMSE 越低代表模型越穩定安全。
rmse = np.sqrt(mean_squared_error(y_test, y_pred))
print(f"RMSE (均方根誤差)   = {rmse:.2f} 萬元")

# 3. R² (決定係數 / Score)：介於 0 到 1 之間。
# 數值代表的含意：代表您的特徵（坪數、捷運距離等）能解釋房價多少百分比的變異。0.8944 代表解釋力高達 89.44%，模型表現良好！
r2 = r2_score(y_test, y_pred)
print(f"R²   (決定係數)     = {r2:.4f}")

# ==============================================================================
# 📊 步驟 8：查看每個特徵的權重係數（Weights & Coefficients）
# ==============================================================================
# 係數為正數：該特徵數值越大，房價通常隨之拉高（正相關）。
# 係數為負數：該特徵數值越大，房價通常隨之暴跌（負相關，如屋齡或捷運距離公尺）。
coef = pd.DataFrame({
    "特徵": X.columns,
    "係數 (權重)": model.named_steps["regressor"].coef_
})
coef = coef.sort_values("係數 (權重)", ascending=False) # 依照影響力由高到低進行排序
print("\n=== [8/11] 各項特徵權重影響力排名 ===")
print(coef)

# ==============================================================================
# 🖼️ 步驟 9：初始化繪圖設定（Data Visualization）
# ==============================================================================
plt.figure(figsize=(6, 6))                                 # 建立一個 6x6 的正方形畫布
plt.scatter(y_test, y_pred, color='blue', alpha=0.6, label="預測房價點") # 繪製散佈圖（藍色圓點）
plt.xlabel("實際房價 (萬元)")                                # 設定 X 軸中文標籤
plt.ylabel("預測房價 (萬元)")                                # 設定 Y 軸中文標籤
plt.title("多變數線性回歸：實際值 vs 預測值 分佈圖")             # 設定圖表大標題

# 繪製一條紅色的斜 45 度理想對角線（完美預測線）
# 如果藍色的點全部完美緊密貼在紅線上，代表模型的預測精準度高達 100%
plt.plot(
    [y_test.min(), y_test.max()],
    [y_test.min(), y_test.max()],
    color="red", linestyle="--", linewidth=2, label="完美預測對角線"
)
plt.legend() # 顯示圖例說明

# ==============================================================================
# 🏠 步驟 10：【完全相容新版 Pandas】使用通用物件型態建立全新房屋案例進行預測
# ==============================================================================
# 先準備一個純 Python 清單，將中壢區設為 1，其他行政區設為 0
# 欄位順序必須與宣告時一致：坪數(35), 屋齡(8), 房間數(3), 樓層(12), 捷運(400), 學校(600), 有車位(1)
# 後續行政區：信義(0), 大安(0), 東區(0), 新店(0), 板橋(0), 中壢(1), 左營(0)
test_values = [35, 8, 3, 12, 400, 600, 1, 0, 0, 0, 0, 0, 1, 0]

# 在建立的當下直接指定 dtype=object，徹底解除 Pandas 對各欄位型態的嚴格鎖定，絕不報錯
new_house = pd.DataFrame([test_values], columns=[
    "坪數", "屋齡", "房間數", "樓層", "捷運距離公尺", "學校距離公尺", "有車位",
    "行政區_台北市信義區", "行政區_台北市大安區", "行政區_台南市東區", 
    "行政區_新北市新店區", "行政區_新北市板橋區", "行政區_桃園市中壢區", "行政區_高雄市左營區"
])

# 自動對齊機制：確保手動建立的表格欄位「順序」，與當初模型訓練（X.columns）時的欄位順序 100% 相同
new_house = new_house[X.columns]

# 呼叫模型進行新房價預測
price_array = np.maximum(model.predict(new_house), 0.0)

# 🛠️ 【本次修正核心】：透過指定索引 [0] 精確取出 NumPy 陣列中的純量數值，完全根除 TypeError 錯誤
predicted_price = float(price_array[0])

print("\n=== [10/11] 實戰物件預測結果 ===")
print(f"該中壢區 35 坪物件之模型預測總價為： {predicted_price:.1f} 萬元")

# ==============================================================================
# 🖥️ 步驟 11：將繪製好的圖形視窗渲染並顯示出來
# ==============================================================================
# 必須放在程式的最後一行！因為圖表跳出時會暫時阻斷（Block）後續程式執行，放在最後可確保上方所有預測文字都已在終端機完整印出。
print("\n=== [11/11] 正在彈出資料分佈視覺化視窗... ===")
plt.show()
